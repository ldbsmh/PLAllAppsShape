#!/bin/sh
# CI/local bootstrap: fetch the Gradle wrapper jar + scripts, then run Gradle.
# Only the tiny bootstrap is vendored; the rest is the official wrapper distribution.
set -e
cd "$(dirname "$0")"
GRADLE_VERSION=8.13

if [ ! -f gradle/wrapper/gradle-wrapper.jar ]; then
  mkdir -p gradle/wrapper
  echo "distributionUrl=https\\://services.gradle.org/distributions/gradle-${GRADLE_VERSION}-bin.zip" \
      > gradle/wrapper/gradle-wrapper.properties
  curl -fsSL -o gradle/wrapper/gradle-wrapper.jar \
      "https://raw.githubusercontent.com/gradle/gradle/v${GRADLE_VERSION}.0/gradle/wrapper/gradle-wrapper.jar"
fi

if [ ! -x gradlew ]; then
  cat > gradlew <<'EOF'
#!/bin/sh
# Generated by bootstrap.sh: plain Gradle invocation, wrapper jar lives next to it.
if [ -n "$GRADLE_USER_HOME" ]; then :; fi
exec java -Xmx2g -classpath gradle/wrapper/gradle-wrapper.jar org.gradle.wrapper.GradleWrapperMain "$@"
EOF
  chmod +x gradlew
fi

case "$1" in
  --setup-only) exit 0 ;;
esac
./gradlew "$@"
